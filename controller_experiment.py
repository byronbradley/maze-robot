"""Reproduce corridor-controller comparisons; results are simulation measurements."""
from pathlib import Path
from wall_following import simulate


def metrics(history, collision):
    errors = [abs(row['offset']) for row in history]
    # First time after which offset remains within 5 mm of center.
    settling = None
    worst_remaining = 0.0
    for row in reversed(history):
        worst_remaining = max(worst_remaining, abs(row['offset']))
        if worst_remaining <= 0.005:
            settling = row['time']
    return collision, errors[-1]*1000, settling


def report():
    lines = ['# Corridor controller experiment', '',
             'Reproduce with `python controller_experiment.py`.', '',
             'All values below are generated by the corridor simulation. '
             'Each case runs for 8 seconds at 10 ms steps in a 30 cm corridor with a 10 cm robot. '
             'The left motor gain is 0.94 and the right is 1.0. Initial offset is 3 cm left.', '',
             'Commands use `kp * (right_range - left_range) + heading_gain * heading`. '
             'Heading feedback is a separate state-feedback term, not a calculated error derivative. '
             'Wheel requests are clamped to 0–0.20 m/s around a 0.12 m/s base speed.', '',
             '| Wall feedback | kp | Heading gain | Wall contact | Final error (mm) | Settling to 5 mm (s) |',
             '|---|---:|---:|---|---:|---:|']
    settings = [(False, 2.0, 0.6)] + [(True, p, h) for p in (0.5, 2.0, 4.0)
                                    for h in (0.0, 0.3, 0.6)]
    for enabled, kp, hg in settings:
        history, collision = simulate(enabled, kp=kp, heading_gain=hg)
        hit, final, settling = metrics(history, collision)
        settled = f'{settling:.2f}' if settling is not None and not hit else '—'
        lines.append(f"| {'on' if enabled else 'off'} | {kp} | {hg} | "
                     f"{'yes' if hit else 'no'} | {final:.2f} | {settled} |")
    lines += ['', '## Default-controller checks', '',
              'The defaults remain kp=2.0 and heading_gain=0.6. '
              'The following cases test both offset directions and reverse the motor mismatch.', '',
              '| Initial offset (cm) | Left/right gain | Dropout | Wall contact | Final error (mm) |',
              '|---:|---|---|---|---:|']
    for offset in (-0.06, 0.06):
        for left, right in ((0.94, 1.0), (1.0, 0.94)):
            for dropout in (None, (2.0, 3.0)):
                history, hit = simulate(initial_offset=offset, left_gain=left,
                                        right_gain=right, dropout_window=dropout)
                lines.append(f"| {offset*100:.0f} | {left}/{right} | "
                             f"{'2–3 s' if dropout else 'none'} | {'yes' if hit else 'no'} | "
                             f"{abs(history[-1]['offset'])*1000:.2f} |")
    lines += ['', '## Interpretation', '',
              'Compare the no-heading-feedback rows with the damped rows to see the effect on settling. '
              'Larger distance gain produces a stronger correction and earlier command saturation; '
              'larger heading gain can slow the return to center. The existing defaults are retained '
              'for comparison. The faster alternatives in this table need comparison across '
              'additional operating conditions before choosing a replacement.', '',
              'This model has ideal wall ranges, direct wheel-speed response, and no slip. '
              'Its gain values cannot be copied into the firmware, where commands are PWM duty '
              'and there is no heading-feedback sensor.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    target = Path(__file__).resolve().parent / 'docs' / 'controller-results.md'
    target.write_text(report(), encoding='utf-8', newline='\n')
    print(target.name)
